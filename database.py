import sqlite3
from datetime import datetime, timedelta

DB_NAME = "volt.db"

def init_db():
    """Initialize database and create tables if they don't exist."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    
    # Users table (premium status, expiration, balance, and last daily claim)
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            is_premium BOOLEAN NOT NULL DEFAULT 0,
            premium_expires TEXT,
            balance INTEGER NOT NULL DEFAULT 0,
            last_daily INTEGER NOT NULL DEFAULT 0
        )
    ''')
    
    # Licenses table generated by the web shop
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS licenses (
            key TEXT PRIMARY KEY,
            duration_days INTEGER NOT NULL,
            is_used BOOLEAN NOT NULL DEFAULT 0
        )
    ''')
    
    conn.commit()
    conn.close()

def check_user_premium(user_id: int) -> bool:
    """Check if the user has an active premium subscription."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    cursor.execute("SELECT is_premium, premium_expires FROM users WHERE user_id = ?", (user_id,))
    row = cursor.fetchone()
    conn.close()

    if not row:
        return False

    is_premium, expires_str = row
    if not is_premium:
        return False

    if expires_str:
        expires_date = datetime.fromisoformat(expires_str)
        if datetime.now() > expires_date:
            remove_premium(user_id)
            return False

    return True

def activate_license(user_id: int, key: str) -> tuple[bool, str]:
    """Activate a license key for a specific user."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()

    cursor.execute("SELECT duration_days, is_used FROM licenses WHERE key = ?", (key,))
    row = cursor.fetchone()

    if not row:
        conn.close()
        return False, "Invalid license key. Please check your code."

    duration_days, is_used = row
    if is_used:
        conn.close()
        return False, "This license key has already been used."

    # Mark key as used
    cursor.execute("UPDATE licenses SET is_used = 1 WHERE key = ?", (key,))

    expires_at = datetime.now() + timedelta(days=duration_days)
    expires_str = expires_at.isoformat()

    # Update or insert user premium status
    cursor.execute('''
        INSERT INTO users (user_id, is_premium, premium_expires, balance)
        VALUES (?, 1, ?, 0)
        ON CONFLICT(user_id) DO UPDATE SET
        is_premium = 1,
        premium_expires = ?
    ''', (user_id, expires_str, expires_str))

    conn.commit()
    conn.close()
    return True, f"Successfully activated Premium for {duration_days} days!"

def remove_premium(user_id: int):
    """Revoke premium status after expiration."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    cursor.execute("UPDATE users SET is_premium = 0, premium_expires = NULL WHERE user_id = ?", (user_id,))
    conn.commit()
    conn.close()

def create_license_key(key: str, duration_days: int = 30):
    """Helper for the web panel to generate a new key after a purchase."""
    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    cursor.execute("INSERT OR IGNORE INTO licenses (key, duration_days, is_used) VALUES (?, ?, 0)", (key, duration_days))
    conn.commit()
    conn.close()
